CREATE TABLE IF NOT EXISTS paises (
  id_pais INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS departamentos (
  id_departamento INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_pais INTEGER NOT NULL REFERENCES paises(id_pais) ON DELETE RESTRICT,
  nombre VARCHAR(100) NOT NULL,
  UNIQUE (nombre, id_pais)
);

CREATE TABLE IF NOT EXISTS ciudades (
  id_ciudad INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_departamento INTEGER NOT NULL REFERENCES departamentos(id_departamento) ON DELETE RESTRICT,
  nombre VARCHAR(100) NOT NULL,
  UNIQUE (nombre, id_departamento)
);

CREATE TABLE IF NOT EXISTS personas (
  identificacion INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_ciudad INTEGER REFERENCES ciudades(id_ciudad) ON DELETE RESTRICT,
  nombre VARCHAR(120) NOT NULL,
  email VARCHAR(254) NOT NULL,
  password_hash TEXT NOT NULL,
  tipo_usuario VARCHAR(20) NOT NULL
    CHECK (tipo_usuario IN ('Cliente', 'Agente', 'Administrador')),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (identificacion, tipo_usuario),
  CHECK (tipo_usuario = 'Administrador' OR id_ciudad IS NOT NULL)
);

CREATE UNIQUE INDEX IF NOT EXISTS personas_email_lower_idx ON personas(LOWER(email));

CREATE TABLE IF NOT EXISTS persona_telefonos (
  identificacion INTEGER NOT NULL REFERENCES personas(identificacion) ON DELETE CASCADE,
  telefono VARCHAR(30) NOT NULL,
  principal BOOLEAN NOT NULL DEFAULT FALSE,
  PRIMARY KEY (identificacion, telefono)
);

CREATE UNIQUE INDEX IF NOT EXISTS persona_telefono_principal_idx
  ON persona_telefonos(identificacion) WHERE principal;

CREATE TABLE IF NOT EXISTS clientes (
  identificacion INTEGER PRIMARY KEY,
  tipo_usuario VARCHAR(20) NOT NULL DEFAULT 'Cliente' CHECK (tipo_usuario = 'Cliente'),
  cantidad_puntos INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_puntos >= 0),
  visualizacion BOOLEAN NOT NULL DEFAULT TRUE,
  publicidad BOOLEAN NOT NULL DEFAULT FALSE,
  FOREIGN KEY (identificacion, tipo_usuario)
    REFERENCES personas(identificacion, tipo_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS agentes (
  identificacion INTEGER PRIMARY KEY,
  tipo_usuario VARCHAR(20) NOT NULL DEFAULT 'Agente' CHECK (tipo_usuario = 'Agente'),
  experiencia INTEGER NOT NULL DEFAULT 0 CHECK (experiencia >= 0),
  comision NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (comision >= 0),
  FOREIGN KEY (identificacion, tipo_usuario)
    REFERENCES personas(identificacion, tipo_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS administradores (
  identificacion INTEGER PRIMARY KEY,
  tipo_usuario VARCHAR(20) NOT NULL DEFAULT 'Administrador' CHECK (tipo_usuario = 'Administrador'),
  salario NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (salario >= 0),
  horario VARCHAR(120) NOT NULL DEFAULT '',
  FOREIGN KEY (identificacion, tipo_usuario)
    REFERENCES personas(identificacion, tipo_usuario) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS estados_reserva (
  id_estado_reserva SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado_reserva VARCHAR(40) NOT NULL UNIQUE
);

INSERT INTO estados_reserva (id_estado_reserva, nombre_estado_reserva)
OVERRIDING SYSTEM VALUE
VALUES
  (1, 'Pendiente'),
  (2, 'Aprobada'),
  (3, 'Rechazada'),
  (4, 'Cancelada')
ON CONFLICT (id_estado_reserva) DO UPDATE
SET nombre_estado_reserva = EXCLUDED.nombre_estado_reserva;

SELECT setval(
  pg_get_serial_sequence('estados_reserva', 'id_estado_reserva'),
  (SELECT COALESCE(MAX(id_estado_reserva), 1) FROM estados_reserva),
  TRUE
);

CREATE TABLE IF NOT EXISTS estados_evento (
  id_estado_evento SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_estado_evento VARCHAR(40) NOT NULL UNIQUE
);

INSERT INTO estados_evento (id_estado_evento, nombre_estado_evento)
OVERRIDING SYSTEM VALUE
VALUES
  (1, 'Programado'),
  (2, 'Cancelado'),
  (3, 'Finalizado')
ON CONFLICT (id_estado_evento) DO UPDATE
SET nombre_estado_evento = EXCLUDED.nombre_estado_evento;

SELECT setval(
  pg_get_serial_sequence('estados_evento', 'id_estado_evento'),
  (SELECT COALESCE(MAX(id_estado_evento), 1) FROM estados_evento),
  TRUE
);

CREATE TABLE IF NOT EXISTS eventos (
  id_evento INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  id_ciudad INTEGER NOT NULL REFERENCES ciudades(id_ciudad) ON DELETE RESTRICT,
  id_estado_evento SMALLINT NOT NULL DEFAULT 1
    REFERENCES estados_evento(id_estado_evento) ON DELETE RESTRICT,
  id_agente INTEGER REFERENCES agentes(identificacion) ON DELETE SET NULL,
  nombre VARCHAR(100) NOT NULL,
  teatro VARCHAR(100) NOT NULL,
  imagen_url TEXT,
  fecha_inicio DATE NOT NULL,
  fecha_fin DATE NOT NULL,
  hora_inicio SMALLINT NOT NULL CHECK (hora_inicio BETWEEN 0 AND 23),
  hora_fin SMALLINT NOT NULL CHECK (hora_fin BETWEEN 0 AND 23),
  descripcion VARCHAR(500) NOT NULL,
  precio_base_entrada NUMERIC(12, 2) NOT NULL CHECK (precio_base_entrada >= 0),
  precio_base NUMERIC(12, 2) NOT NULL CHECK (precio_base >= 0),
  capacidad_total INTEGER NOT NULL CHECK (capacidad_total > 0),
  observaciones VARCHAR(500) NOT NULL DEFAULT '',
  causa_cancelacion VARCHAR(500),
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (fecha_fin >= fecha_inicio),
  CHECK (
    (id_estado_evento = 2 AND NULLIF(BTRIM(causa_cancelacion), '') IS NOT NULL)
    OR (id_estado_evento <> 2 AND causa_cancelacion IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS reservas (
  id_reserva INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  identificacion INTEGER NOT NULL REFERENCES clientes(identificacion) ON DELETE RESTRICT,
  id_evento INTEGER NOT NULL REFERENCES eventos(id_evento) ON DELETE RESTRICT,
  id_estado_reserva SMALLINT NOT NULL DEFAULT 1
    REFERENCES estados_reserva(id_estado_reserva) ON DELETE RESTRICT,
  fecha_solicitud TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  hora TIME NOT NULL DEFAULT LOCALTIME,
  cantidad_entradas INTEGER NOT NULL CHECK (cantidad_entradas > 0),
  observaciones VARCHAR(500) NOT NULL DEFAULT '',
  valor_total NUMERIC(12, 2) NOT NULL CHECK (valor_total >= 0),
  causa_cancelacion VARCHAR(500),
  CHECK (
    (id_estado_reserva = 4 AND NULLIF(BTRIM(causa_cancelacion), '') IS NOT NULL)
    OR (id_estado_reserva <> 4 AND causa_cancelacion IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS reservas_cliente_idx ON reservas(identificacion);
CREATE INDEX IF NOT EXISTS reservas_evento_idx ON reservas(id_evento);
CREATE INDEX IF NOT EXISTS reservas_estado_idx ON reservas(id_estado_reserva);
CREATE INDEX IF NOT EXISTS eventos_fecha_idx ON eventos(fecha_inicio);
CREATE INDEX IF NOT EXISTS eventos_agente_ciudad_idx ON eventos(id_agente, id_ciudad);
CREATE INDEX IF NOT EXISTS personas_ciudad_idx ON personas(id_ciudad);
